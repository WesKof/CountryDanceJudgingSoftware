import { test, expect } from '@playwright/test';
import { createStage, limitedStage } from './publication-helpers';
import { api, command, save, submitHeat, base } from './stage-helpers';
import type { LiveView } from '../lib/live/types';

test('organizer watches draft and locked scores through polling with stable view controls on phone and desktop', async ({ page }) => {
  const { organizer, tokens } = await createStage(limitedStage(1, 2));
  await page.goto(`${base}/?event=${organizer}`);
  await page.getByRole('button', { name: '02 Score' }).click();
  const card = page.locator('#run-live-scores');
  await expect(card).not.toHaveAttribute('open', '');
  await page.getByRole('button', { name: 'View live scores', exact: true }).click();
  await expect(card).toHaveAttribute('open', '');
  await expect(card.locator(':scope > summary')).toBeFocused();
  await expect(card.getByText('Start this round to see judging progress.')).toBeVisible();
  await command(organizer, { action: 'open-stage', kind: 'prelims' });
  const initial = await api<LiveView>(organizer), round = initial.rounds[0], heat = round.definition.heats[0];
  const [song1, song2] = heat.songs;
  await expect(card.locator('table')).toBeVisible({ timeout: 12000 });
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '0');
  const row = card.locator('tbody tr').first();
  await expect(row.locator('td').first()).toHaveText('Not scored');
  await save(tokens[0], round, song1.id, heat.subjectIds[0], 'Yes', 'PRIVATE_BROWSER_SCORE_NOTE');
  await expect(row.locator('td').first()).toHaveText('Yes', { timeout: 12000 });
  await save(tokens[0], round, song1.id, heat.subjectIds[0], 'No');
  await expect(row.locator('td').first()).toHaveText('No · 0', { timeout: 12000 });
  await save(tokens[0], round, song1.id, heat.subjectIds[1], '');
  await expect(card.locator('tbody tr').nth(1).locator('td').first()).toHaveText('Blank', { timeout: 12000 });
  await card.getByLabel('Live scores song').selectOption(song1.id);
  await command(organizer, { action: 'next' });
  await save(tokens[0], round, song2.id, heat.subjectIds[1], 'A1');
  await command(organizer, { action: 'lineup' });
  await submitHeat(tokens[0], round, heat.id);
  await expect(card.locator('thead th').nth(1)).toContainText('Submitted · locked', { timeout: 12000 });
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '1');
  await expect(card.getByLabel('Live scores song')).toHaveValue(song1.id);
  await expect(row.locator('td').first()).toHaveText('No · 0');
  await expect(card.locator('input, textarea')).toHaveCount(0);
  await expect(card).not.toContainText('PRIVATE_BROWSER_SCORE_NOTE');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(card).toHaveAttribute('open', '');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await card.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'work/live-scores-390.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'work/live-scores-1440.png', fullPage: true });
  await card.getByRole('button', { name: 'Follow current song' }).click();
  await expect(card.getByLabel('Live scores song')).toHaveValue(song2.id);
  const finals = initial.setup.rounds.find((r) => r.kind === 'finals')!;
  await page.getByLabel('Competition and round view', { exact: true }).selectOption(finals.id);
  await expect(card.getByText('Start this round to see judging progress.')).toBeVisible();
  expect((await api<LiveView>(organizer)).context.performanceId).toBe(song2.id);
  await page.getByLabel('Competition and round view', { exact: true }).selectOption(round.id);
  await page.route('**/api/live', (route) => route.request().method() === 'GET' ? route.abort() : route.continue());
  await expect(card.getByRole('status')).toContainText('Last connected scores', { timeout: 12000 });
  await expect(card.locator('thead th').nth(1)).toContainText('Submitted · locked');
  await page.unroute('**/api/live');
  await expect(card.getByRole('status')).toHaveCount(0, { timeout: 12000 });
});
