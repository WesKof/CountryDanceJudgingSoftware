import { test, expect, type Page, type Locator } from '@playwright/test';
import { createStage, limitedStage, dance, exact } from './publication-helpers';
import { api, base, command, save, submitHeat } from './stage-helpers';
import type { LiveView } from '../lib/live/types';

async function click(page: Page, button: Locator, action: string) {
  const response = page.waitForResponse((r) => r.url().endsWith('/api/live') && r.request().method() === 'POST' && r.request().postDataJSON()?.action === action);
  await button.click();
  expect((await response).status()).toBe(200);
}

test('head review recovers after a revised correction is cancelled and preserves private scorecards', async ({ browser }) => {
  const setup = limitedStage(1, 4), { organizer, tokens, head, path } = await createStage(setup);
  await command(organizer, { action: 'open-stage', kind: 'prelims' });
  let view = await api<LiveView>(organizer), round = view.rounds[0];
  await dance(organizer, tokens, round);
  await command(organizer, { action: 'conclude-stage' });
  view = await api<LiveView>(organizer); round = view.rounds[0];
  const source = view.heatSubmissions!.find((s) => s.judgeId === setup.judges[0].id)!;
  const request = { action: 'request-correction', roundKey: round.key, heatId: source.heatId, judgeId: source.judgeId, submissionId: source.id, reason: 'Synthetic correction to cancel', changes: [{ performanceId: round.definition.heats[0].songs[0].id, subjectId: round.definition.subjects[0].id, after: 'A1' }] };
  const created = await command(organizer, request) as { reviewRequestId: string };
  await command(organizer, { ...request, reviewRequestId: created.reviewRequestId, reason: 'Synthetic revised correction to cancel' });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const desk = await context.newPage(), headPage = await context.newPage(), judge = await context.newPage();
  const errors: string[] = [];
  for (const page of [desk, headPage, judge]) page.on('pageerror', (e) => errors.push(e.message));
  await headPage.goto(base + view.judgeLinks!.find((j) => j.path.endsWith(head))!.path);
  const approve = headPage.getByRole('button', { name: 'Approve these exact submissions', exact: true });
  await expect(approve).toBeDisabled();
  await desk.goto(base + path);
  await desk.getByRole('button', { name: '03 Results', exact: true }).click();
  await desk.locator('details.setup-section').filter({ has: desk.getByRole('heading', { name: 'Amendments & withdrawals', exact: true }) }).locator(':scope > summary').click();
  await click(desk, desk.getByRole('button', { name: 'Cancel request', exact: true }), 'cancel-request');
  await headPage.reload();
  await expect(headPage.getByText('Cancelled; records retained', { exact: true })).toBeVisible();
  await expect(approve).toBeEnabled();
  await expect(headPage.getByLabel('Current and past songs', { exact: true })).toHaveCount(0);
  await expect(headPage.getByText(/This stage’s submitted scores are locked/)).toBeVisible();
  await expect(headPage.getByText('PUBLICATION_PRIVATE_NOTE_SENTINEL', { exact: false })).toHaveCount(0);
  await judge.goto(base + view.judgeLinks![0].path);
  await judge.getByText('My private submitted notes', { exact: true }).click();
  await expect(judge.getByText(/PUBLICATION_PRIVATE_NOTE_SENTINEL/)).toBeVisible();
  for (const width of [360, 390, 1440]) {
    await headPage.setViewportSize({ width, height: 900 });
    expect(await headPage.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
    expect(await headPage.locator('.result-group .table-wrap').evaluate((table) => table.scrollWidth <= table.clientWidth)).toBe(true);
    await headPage.screenshot({ path: `test-results/cleanup-head-ready-${width}.png`, fullPage: false });
  }
  await click(headPage, approve, 'approve');
  view = await api<LiveView>(organizer);
  expect(view.rounds[0].standings!.approved).toBe(true);
  expect(view.rounds[0].standings!.rows[0].average).toBe(10);
  expect(view.reviewRequests!.find((q) => q.id === created.reviewRequestId)?.cancelledAt).toBeTruthy();
  expect(view.heatSubmissions).toHaveLength(3);
  await context.close(); expect(errors).toEqual([]);
});

test('archived review keeps votes and correction management read only while preserving submitted records', async ({ browser }) => {
  const setup = limitedStage(1, 4), { organizer, tokens, path } = await createStage(setup);
  await command(organizer, { action: 'open-stage', kind: 'prelims' });
  let view = await api<LiveView>(organizer);
  const round = view.rounds[0], heat = round.definition.heats[0];
  for (const token of tokens) for (const subject of heat.subjectIds) await save(token, round, heat.songs[0].id, subject, 'Yes');
  await command(organizer, { action: 'next' }); await command(organizer, { action: 'lineup' });
  await Promise.all(tokens.map((token) => submitHeat(token, round, heat.id)));
  await command(organizer, { action: 'conclude-stage' });
  view = await api<LiveView>(organizer);
  const source = view.heatSubmissions![0];
  const created = await command(organizer, { action: 'request-correction', roundKey: round.key, heatId: source.heatId, judgeId: source.judgeId, submissionId: source.id, reason: 'Synthetic archived pending request', changes: [{ performanceId: heat.songs[0].id, subjectId: heat.subjectIds[0], after: 'A1' }] }) as { reviewRequestId: string };
  await command(organizer, { action: 'archive' });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } }), judge = await context.newPage(), desk = await context.newPage();
  await judge.goto(base + view.judgeLinks![0].path);
  const votes = judge.getByRole('group', { name: 'Beginner / Intermediate · Couples advancement tie', exact: true });
  await expect(judge.getByText('Archived · read only', { exact: true })).toBeVisible();
  await expect(votes).toBeVisible();
  for (const checkbox of await votes.getByRole('checkbox').all()) await expect(checkbox).toBeDisabled();
  await expect(votes.getByRole('button', { name: 'Submit advancement vote', exact: true })).toBeDisabled();
  await desk.goto(base + path); await desk.getByRole('button', { name: '03 Results', exact: true }).click();
  await desk.locator('details.setup-section').filter({ has: desk.getByRole('heading', { name: 'Amendments & withdrawals', exact: true }) }).locator(':scope > summary').click();
  await expect(desk.getByRole('button', { name: 'Cancel request', exact: true })).toBeDisabled();
  const withdrawals = desk.locator('details.setup-section').filter({ has: desk.getByRole('heading', { name: 'Withdraw a started entrant/couple', exact: true }) }).last();
  await withdrawals.locator(':scope > summary').click();
  await expect(withdrawals.getByRole('button', { name: 'Request entrant withdrawal', exact: true })).toBeDisabled();
  await expect(desk.getByText('Revise this pending correction', { exact: true })).toHaveCount(0);
  await command(organizer, { action: 'cancel-request', reviewRequestId: created.reviewRequestId, requestVersion: 1 }, 423);
  view = await api<LiveView>(organizer);
  expect(view.status).toBe('archived'); expect(view.reviewRequests![0].cancelledAt).toBeUndefined();
  expect(view.heatSubmissions).toHaveLength(3);
  expect(view.rounds[0].standings!.rows.every((row) => row.average === 10)).toBe(true);
  await context.close();
});

test('a pending Finals correction blocks head approval until both exact approvals apply it', async ({ browser }) => {
  const setup = limitedStage(1, 4), { organizer, tokens, head } = await createStage(setup);
  await command(organizer, { action: 'open-stage', kind: 'prelims' });
  let view = await api<LiveView>(organizer);
  await dance(organizer, tokens, view.rounds[0]);
  await command(organizer, { action: 'conclude-stage' });
  await exact(head, view.rounds[0].id, 'approve');
  await command(organizer, { action: 'open-stage', kind: 'finals' });
  view = await api<LiveView>(organizer);
  let round = view.rounds.find((r) => r.definition.kind === 'finals')!;
  await dance(organizer, tokens, round);
  await command(organizer, { action: 'conclude-stage' });
  view = await api<LiveView>(organizer); round = view.rounds.find((r) => r.definition.kind === 'finals')!;
  const source = view.heatSubmissions!.find((s) => s.roundKey === round.key && s.judgeId === setup.judges[0].id)!;
  const created = await command(organizer, { action: 'request-correction', roundKey: round.key, heatId: source.heatId, judgeId: source.judgeId, submissionId: source.id, reason: 'Synthetic Finals recording error', changes: [{ performanceId: round.definition.heats[0].songs[0].id, subjectId: round.definition.subjects[0].id, after: 'A1' }] }) as { reviewRequestId: string };
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } }), page = await context.newPage();
  await page.goto(base + view.judgeLinks!.find((j) => j.path.endsWith(head))!.path);
  const results = page.locator('.result-sheet').filter({ hasText: '· finals' });
  const approve = results.getByRole('button', { name: 'Approve these exact submissions', exact: true });
  await expect(approve).toBeDisabled();
  expect(await approve.evaluate((button) => Boolean(button.compareDocumentPosition(button.closest('.result-sheet')!.querySelector('table')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
  await expect(results.getByText(/Resolve the pending recording-error correction/)).toBeVisible();
  await results.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/cleanup-head-blocked-390.png', fullPage: false });
  await results.getByRole('button', { name: 'Review pending corrections', exact: true }).click();
  await expect(page.locator(`#review-request-${created.reviewRequestId}`)).toBeFocused();
  await expect(page.locator(`#review-request-${created.reviewRequestId}`).getByText('Synthetic Finals recording error', { exact: true })).toBeVisible();
  page.once('dialog', (d) => void d.accept());
  await click(page, page.getByRole('button', { name: 'Approve request as head', exact: true }), 'approve-request');
  await expect(approve).toBeDisabled();
  await command(organizer, { action: 'approve-request', reviewRequestId: created.reviewRequestId, requestVersion: 1 });
  await page.reload(); await expect(approve).toBeEnabled();
  await click(page, approve, 'approve');
  view = await api<LiveView>(organizer); round = view.rounds.find((r) => r.definition.kind === 'finals')!;
  expect(round.standings!.approved).toBe(true);
  expect(round.standings!.rows[0].average).toBeCloseTo(24.5 / 3, 10);
  expect(view.heatSubmissions!.filter((s) => s.roundKey === round.key)).toHaveLength(3);
  expect(view.heatSubmissions!.find((s) => s.judgeId === source.judgeId && s.roundKey === round.key)?.supersedes).toBe(source.id);
  const backup = await command(organizer, { action: 'backup' }) as { history: { heatSubmissions: { id: string; roundKey: string }[] } };
  expect(backup.history.heatSubmissions.filter((s) => s.roundKey === round.key)).toHaveLength(4);
  expect(backup.history.heatSubmissions.some((s) => s.id === source.id)).toBe(true);
  expect(view.reviewRequests!.find((q) => q.id === created.reviewRequestId)?.approvals).toHaveLength(2);
  await context.close();
});
